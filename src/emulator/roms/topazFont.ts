/**
 * Fast planar pixel & rectangle writer directly into Amiga Chip RAM bitplanes.
 * Layout: `numPlanes` contiguous planes starting at `baseAddr`, each `planeSize` bytes (40*256 = 10240 bytes for 320x256).
 */
export class PlanarCanvas {
  public readonly baseAddr: number;
  public readonly width = 320;
  public readonly height = 256;
  public readonly rowBytes = 40;
  public readonly planeSize = 40 * 256; // 10240 bytes per plane
  public numPlanes: number;

  constructor(baseAddr = 0x020000, numPlanes = 4) {
    this.baseAddr = baseAddr;
    this.numPlanes = numPlanes;
  }

  public clear(chipRam: Uint8Array, colorIdx = 0): void {
    for (let p = 0; p < this.numPlanes; p++) {
      const fill = (colorIdx & (1 << p)) !== 0 ? 0xff : 0x00;
      const off = this.baseAddr + p * this.planeSize;
      chipRam.fill(fill, off, off + this.planeSize);
    }
  }

  public setPixel(chipRam: Uint8Array, x: number, y: number, colorIdx: number): void {
    const ix = x | 0;
    const iy = y | 0;
    if (ix < 0 || ix >= 320 || iy < 0 || iy >= 256) return;
    const byteOff = iy * 40 + (ix >>> 3);
    const bitMask = 0x80 >>> (ix & 7);
    const invMask = ~bitMask & 0xff;
    for (let p = 0; p < this.numPlanes; p++) {
      const addr = this.baseAddr + p * this.planeSize + byteOff;
      if ((colorIdx & (1 << p)) !== 0) {
        chipRam[addr] |= bitMask;
      } else {
        chipRam[addr] &= invMask;
      }
    }
  }

  public fillRect(
    chipRam: Uint8Array,
    x: number,
    y: number,
    w: number,
    h: number,
    colorIdx: number
  ): void {
    const x0 = Math.max(0, x | 0);
    const y0 = Math.max(0, y | 0);
    const x1 = Math.min(320, (x + w) | 0);
    const y1 = Math.min(256, (y + h) | 0);
    if (x0 >= x1 || y0 >= y1) return;

    const firstByte = x0 >>> 3;
    const lastByte = (x1 - 1) >>> 3;
    const leftMask = 0xff >>> (x0 & 7);
    const rightMask = (0xff << (7 - ((x1 - 1) & 7))) & 0xff;

    for (let p = 0; p < this.numPlanes; p++) {
      const setBit = (colorIdx & (1 << p)) !== 0;
      const planeOff = this.baseAddr + p * this.planeSize;
      const fillByte = setBit ? 0xff : 0x00;

      for (let row = y0; row < y1; row++) {
        const rowBase = planeOff + row * 40;
        if (firstByte === lastByte) {
          const m = leftMask & rightMask;
          if (setBit) chipRam[rowBase + firstByte] |= m;
          else chipRam[rowBase + firstByte] &= ~m;
        } else {
          if (setBit) chipRam[rowBase + firstByte] |= leftMask;
          else chipRam[rowBase + firstByte] &= ~leftMask;

          if (lastByte - firstByte > 1) {
            chipRam.fill(fillByte, rowBase + firstByte + 1, rowBase + lastByte);
          }

          if (setBit) chipRam[rowBase + lastByte] |= rightMask;
          else chipRam[rowBase + lastByte] &= ~rightMask;
        }
      }
    }
  }

  public strokeRect(
    chipRam: Uint8Array,
    x: number,
    y: number,
    w: number,
    h: number,
    colorIdx: number
  ): void {
    this.fillRect(chipRam, x, y, w, 1, colorIdx);
    this.fillRect(chipRam, x, y + h - 1, w, 1, colorIdx);
    this.fillRect(chipRam, x, y, 1, h, colorIdx);
    this.fillRect(chipRam, x + w - 1, y, 1, h, colorIdx);
  }

  public fillCircle(
    chipRam: Uint8Array,
    cx: number,
    cy: number,
    r: number,
    colorIdx: number
  ): void {
    const r2 = r * r;
    for (let dy = -r; dy <= r; dy++) {
      const dxMax = Math.floor(Math.sqrt(r2 - dy * dy));
      this.fillRect(chipRam, cx - dxMax, cy + dy, dxMax * 2 + 1, 1, colorIdx);
    }
  }

  public drawText(
    chipRam: Uint8Array,
    x: number,
    y: number,
    text: string,
    fgColor: number,
    bgColor = -1
  ): void {
    let curX = x | 0;
    const upper = text.toUpperCase();
    for (let i = 0; i < upper.length; i++) {
      const ch = upper.charCodeAt(i);
      const glyph = FONT_8X8[ch] ?? FONT_8X8[63];
      for (let row = 0; row < 8; row++) {
        const py = y + row;
        if (py < 0 || py >= 256) continue;
        const bits = glyph[row];
        for (let col = 0; col < 8; col++) {
          const px = curX + col;
          if (px < 0 || px >= 320) continue;
          if ((bits & (0x80 >>> col)) !== 0) {
            this.setPixel(chipRam, px, py, fgColor);
          } else if (bgColor >= 0) {
            this.setPixel(chipRam, px, py, bgColor);
          }
        }
      }
      curX += 8;
    }
  }
}

/**
 * Helper to write Copper MOVE / WAIT instructions into Chip RAM.
 */
export class CopperBuilder {
  private addr: number;
  private readonly chipRam: Uint8Array;

  constructor(chipRam: Uint8Array, startAddr = 0x008000) {
    this.chipRam = chipRam;
    this.addr = startAddr;
  }

  public move(regOffset: number, value: number): this {
    const r = regOffset & 0x01fe;
    const v = value & 0xffff;
    this.chipRam[this.addr++] = (r >>> 8) & 0xff;
    this.chipRam[this.addr++] = r & 0xff;
    this.chipRam[this.addr++] = (v >>> 8) & 0xff;
    this.chipRam[this.addr++] = v & 0xff;
    return this;
  }

  public wait(vpos: number, hpos = 0x07): this {
    const w1 = ((vpos & 0xff) << 8) | (hpos & 0xfe) | 1;
    const w2 = 0xfffe;
    this.chipRam[this.addr++] = (w1 >>> 8) & 0xff;
    this.chipRam[this.addr++] = w1 & 0xff;
    this.chipRam[this.addr++] = (w2 >>> 8) & 0xff;
    this.chipRam[this.addr++] = w2 & 0xff;
    return this;
  }

  public setBitplanes(baseAddr: number, numPlanes: number, planeSize = 10240): this {
    for (let p = 0; p < numPlanes; p++) {
      const ptr = baseAddr + p * planeSize;
      const reg = 0x0e0 + p * 4;
      this.move(reg, (ptr >>> 16) & 0x1f);
      this.move(reg + 2, ptr & 0xffff);
    }
    return this;
  }

  public setPalette(colors: number[]): this {
    for (let i = 0; i < colors.length && i < 32; i++) {
      this.move(0x180 + i * 2, colors[i]);
    }
    return this;
  }

  public end(): this {
    this.chipRam[this.addr++] = 0xff;
    this.chipRam[this.addr++] = 0xff;
    this.chipRam[this.addr++] = 0xff;
    this.chipRam[this.addr++] = 0xfe;
    return this;
  }
}
